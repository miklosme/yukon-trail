import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {journalEditOpeningText,win16EditText} from '../web/platform/text.mjs';
const evidence=JSON.parse(readFileSync(new URL('../docs/journal-edit-reopen-evidence.json',import.meta.url)));
const prior=Buffer.from(evidence.prior_text_hex,'hex').toString('latin1');
const after=Buffer.from(evidence.after_text_hex,'hex').toString('latin1');
assert.equal(journalEditOpeningText(prior),after,'Must match independently captured original reopen save bytes');
assert.equal(win16EditText(prior.replace(/\r\n/g,'\n')),prior);
assert.equal(journalEditOpeningText(prior.replace(/\r\n/g,'\n')),after);
assert.throws(()=>journalEditOpeningText('a'.repeat(0x27ff)),RangeError);
assert.throws(()=>journalEditOpeningText('\u0100'),TypeError);
assert.throws(()=>journalEditOpeningText('\0'),TypeError);
console.log('Journal Edit insertion matches original JPRE/JPOST save text; DOM caret and capacity behavior excluded');
